const audioDetails = [
  [/^Не удалось подключить микрофон\. Код (\d+)\.$/, 'Could not connect the microphone. Error $1.'],
  [/^Не удалось получить звук\. Код (0x[0-9A-F]+)\.$/, 'Could not capture audio. Error $1.'],
  [/^VST3 не поддерживает этот формат микрофона: (\d+) Гц\.$/, 'The VST3 does not support this microphone sample rate ($1 Hz).']
];

function localizeMessage(message, language) {
  if (!message) return '';
  if (Object.hasOwn(strings.ru, message) && typeof strings.ru[message] === 'string') return strings[language][message];
  if (language === 'ru') return message;
  for (const [prefix, translation] of [
    ['Прослушивание остановилось. ', 'Monitoring stopped. '],
    ['Не удалось включить прослушивание. ', 'Could not start monitoring. ']
  ]) {
    if (message.startsWith(prefix)) return translation + localizeMessage(message.slice(prefix.length), language);
  }
  const direct = audioMessages.get(message);
  if (direct) return direct;
  const detail = audioDetails.find(([pattern]) => pattern.test(message));
  return detail ? message.replace(...detail) : message;
}

